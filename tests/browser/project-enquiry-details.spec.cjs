const {test,expect}=require('@playwright/test');
const {mockWorkspace,tables}=require('./fixtures.cjs');
for(const role of ['admin','project_manager'])test(`${role} can edit previously filled enquiry details from a project and reload them`,async({page})=>{
 const {calls}=await mockWorkspace(page,{role});let saved;
 await page.route('**/rest/v1/leads?*',route=>route.fulfill({json:[{...tables.leads[0],phone:'+1 555 0100',designation:'Founder',company_website:'https://northstar.example',country:'USA',industry:'Professional Services',budget_range:'$5,000–$10,000',budget_shared:true,urgency:'Rush',source:'Direct email',acquisition_source:'Referral'}]}));
 await page.route('**/rest/v1/projects?*',route=>route.fulfill({json:[{...tables.projects[0],...(saved||{})}]}));
 await page.goto('/projects/EVE-2026-001');await page.getByRole('button',{name:'Edit project',exact:true}).click();
 const form=page.getByRole('dialog',{name:'Edit project details'});
 await expect(form.getByLabel('Phone number',{exact:true})).toHaveValue('+1 555 0100');
 await expect(form.getByLabel('Designation',{exact:true})).toHaveValue('Founder');
 await expect(form.getByLabel('Company website',{exact:true})).toHaveValue('https://northstar.example');
 await expect(form.getByLabel('Original enquiry goals',{exact:true})).toHaveValue(tables.leads[0].description);
 await form.getByLabel('Phone number',{exact:true}).fill('+91 9000000000');
 await form.getByLabel('Designation',{exact:true}).fill('Director');
 await form.getByLabel('Company website',{exact:true}).fill('https://updated.example');
 await form.getByLabel('Country',{exact:true}).fill('India');
 await form.getByLabel('Timezone',{exact:true}).fill('Asia/Kolkata');
 await form.getByLabel('Industry',{exact:true}).fill('Technology');
 await form.getByLabel('Original enquiry goals',{exact:true}).fill('Updated project requirements');
 await form.getByLabel('Reference links',{exact:true}).fill('https://reference.example');
 await form.getByLabel('Estimated budget range',{exact:true}).fill('$10,000–$25,000');
 await form.getByLabel('Budget notes',{exact:true}).fill('Budget approved');
 await form.getByRole('combobox',{name:'Urgency',exact:true}).selectOption('Standard');
 await form.getByLabel('Enquiry source',{exact:true}).fill('Phone / WhatsApp');
 await form.getByLabel('Acquisition source',{exact:true}).fill('Repeat client');
 await form.getByRole('button',{name:'Save changes',exact:true}).click();await expect(form).not.toBeVisible();
 const changes=calls.flatMap(call=>call.p_changes);expect(changes).toHaveLength(1);expect(changes[0].collection).toBe('projects');
 saved=changes[0].data.row;
 expect(saved.enquiry_details).toMatchObject({phone:'+91 9000000000',designation:'Director',companyWebsite:'https://updated.example',country:'India',timezone:'Asia/Kolkata',industry:'Technology',description:'Updated project requirements',referenceLinks:'https://reference.example',budgetRange:'$10,000–$25,000',budgetShared:true,budgetNote:'Budget approved',urgency:'Standard',source:'Phone / WhatsApp',acquisitionSource:'Repeat client'});
 await page.reload();await page.getByRole('button',{name:'Edit project',exact:true}).click();
 await expect(form.getByLabel('Phone number',{exact:true})).toHaveValue('+91 9000000000');
 await expect(form.getByLabel('Country',{exact:true})).toHaveValue('India');
 await expect(form.getByLabel('Original enquiry goals',{exact:true})).toHaveValue('Updated project requirements');
});
test('a project without a linked lead can save its own phone and contact details',async({page})=>{
 const {calls}=await mockWorkspace(page);
 await page.route('**/rest/v1/projects?*',route=>route.fulfill({json:[{...tables.projects[0],lead_id:null,client_email:'independent@example.com',enquiry_details:{phone:'+44 1000',country:'UK'}}]}));
 await page.goto('/projects/EVE-2026-001');await page.getByRole('button',{name:'Edit project',exact:true}).click();
 const form=page.getByRole('dialog',{name:'Edit project details'});
 await expect(form.getByLabel('Phone number',{exact:true})).toHaveValue('+44 1000');
 await form.getByLabel('Phone number',{exact:true}).fill('+44 2000');
 await form.getByRole('button',{name:'Save changes',exact:true}).click();await expect(form).not.toBeVisible();
 expect(calls.flatMap(call=>call.p_changes)[0].data.row.enquiry_details.phone).toBe('+44 2000');
});
