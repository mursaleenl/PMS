const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const sources = [
  'schema.sql',
  'workspace-reliability-migration.sql',
  'employee-role-access-migration.sql',
  'employee-client-rls-fix.sql',
  'reviews-migration.sql',
  'qr-attendance-migration.sql',
  'client-portal-access-migration.sql',
  'project-status-migration.sql',
  'project-assignment-status-migration.sql',
  'activity-notifications-migration.sql',
  'client-project-tasks-migration.sql',
];
const header = `-- Generated by node scripts/build-testing-database.cjs. Do not edit directly.
-- Repository-defined application schema, NOT a live production export.
-- Run ONLY in a fresh Supabase testing project. No production data or users included.
-- Supabase supplies auth.users, auth.uid(), auth.jwt(), and platform roles.
-- The whole installation rolls back on failure.
begin;
do $$
begin
  if exists (select 1 from information_schema.tables where table_schema='public' and table_type='BASE TABLE') then
    raise exception 'Testing setup requires a fresh public schema. Select an empty testing project.';
  end if;
end;
$$;
`;
const sql = header + sources.map(file => {
  const body = fs.readFileSync(path.join(root, 'supabase', file), 'utf8')
    .replace(/^\s*(?:begin|commit);\s*$/gmi, '');
  return `\n-- ===== Source: ${file} =====\n${body.trim()}\n`;
}).join('') + '\ncommit;\n';
fs.writeFileSync(path.join(root, 'supabase/testing-database.sql'), sql);
console.log(`Generated supabase/testing-database.sql from ${sources.length} ordered sources.`);
